"""Check site/data/features.json against the app and write docs/FEATURE_INVENTORY.md from it.

    python scripts/build_feature_inventory.py [--check]

Checks, and fails (exit 1) on any problem:
  - every label quoted for a feature is a string the app really shows (a literal in
    app/spatial/copy.py, the QML files, the Security Lab, the lesson, the challenges or
    the classic window);
  - every test file exists and every named test is defined in it;
  - no long dash anywhere in the inventory.
With --check nothing is written; otherwise the Markdown file is written as well.
"""
from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FEATURES = ROOT / "site" / "data" / "features.json"
OUT = ROOT / "docs" / "FEATURE_INVENTORY.md"
PY_SOURCES = ["app/spatial/copy.py", "pqsse/attacklab.py", "app/lesson.py", "app/challenges.py", "app/main.py"]
LONG_DASHES = (chr(0x2013), chr(0x2014))


def python_strings(path: Path) -> set[str]:
    """Every string constant in a Python file (labels, titles, tab names)."""
    found = set()
    for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            found.add(node.value)
    return found


def qml_strings(path: Path) -> set[str]:
    return set(re.findall(r'"((?:[^"\\]|\\.)*)"', path.read_text(encoding="utf-8")))


def app_strings() -> set[str]:
    strings: set[str] = set()
    for rel in PY_SOURCES:
        strings |= python_strings(ROOT / rel)
    for qml in (ROOT / "app" / "spatial" / "qml").glob("*.qml"):
        strings |= qml_strings(qml)
    return strings


def defined_tests(path: Path) -> set[str]:
    return set(re.findall(r"^(?:async\s+)?def (test_\w+)\(", path.read_text(encoding="utf-8"), re.M))


def check(data: dict) -> list[str]:
    problems = []
    strings = app_strings()
    group_ids = {g["id"] for g in data["groups"]}
    seen = set()
    for f in data["features"]:
        fid = f["id"]
        if fid in seen:
            problems.append(f"{fid}: duplicate id")
        seen.add(fid)
        if f["group"] not in group_ids:
            problems.append(f"{fid}: unknown group {f['group']}")
        if f["status"] not in ("verified", "tested", "partial", "not-verified"):
            problems.append(f"{fid}: unknown status {f['status']}")
        for label in f["where"]["labels"]:
            if label not in strings:
                problems.append(f"{fid}: the label '{label}' is not a string the app shows")
        for t in f["tests"]:
            path = ROOT / t["file"]
            if not path.is_file():
                problems.append(f"{fid}: no test file {t['file']}")
                continue
            missing = set(t["names"]) - defined_tests(path)
            for name in sorted(missing):
                problems.append(f"{fid}: {t['file']} has no test {name}")
    text = FEATURES.read_text(encoding="utf-8")
    if any(d in text for d in LONG_DASHES):
        problems.append("features.json contains a long dash")
    return problems


def tests_line(f: dict) -> str:
    parts = []
    for t in f["tests"]:
        count = len(defined_tests(ROOT / t["file"]))
        if t["names"]:
            parts.append(f"`{t['file']}`: " + ", ".join(f"`{n}`" for n in t["names"]) + f" ({count} tests in the file)")
        else:
            parts.append(f"`{t['file']}` (all {count} tests)")
    return "; ".join(parts) or "none"


STATUS = {"verified": "Verified: seen in the running app and covered by tests",
          "tested": "Tested: covered by automated tests, not looked at by hand in this pass",
          "partial": "Partial: works, with the gap named under Limits",
          "not-verified": "Not verified: implemented, never run here"}


def render(data: dict) -> str:
    out = ["# Feature inventory",
           "",
           "What PQ-SSE Desktop really does, feature by feature. Generated from `site/data/features.json` by",
           "`scripts/build_feature_inventory.py`, which also checks that every quoted label is a string the app",
           "shows and that every named test exists. Do not edit this file by hand.",
           "",
           "Sources: `app/spatial/copy.py` (labels), `app/spatial/qml/` (screens), `pqsse/` (behaviour),",
           "`tests/` (evidence), and a run of the app on 2026-11-18 (`scripts/spatial_shots.py`, 12 lesson steps,",
           "screenshots of every screen).",
           "",
           "Status: " + "; ".join(f"**{k}**" for k in STATUS) + ".",
           ""]
    titles = {g["id"]: g["title"] for g in data["groups"]}
    total = len(data["features"])
    counts = {k: sum(1 for f in data["features"] if f["status"] == k) for k in STATUS}
    out += [f"{total} features: " + ", ".join(f"{n} {k}" for k, n in counts.items() if n) + ".", ""]
    for gid, title in titles.items():
        feats = [f for f in data["features"] if f["group"] == gid]
        if not feats:
            continue
        out += [f"## {title}", ""]
        for f in feats:
            w = f["where"]
            out += [f"### {f['name']}", "", f["sentence"], "",
                    f"- **Who uses it:** {', '.join(f['users'])}",
                    f"- **Where:** {w['screen']}" + (f"; labels: " + ", ".join(f"\"{l}\"" for l in w["labels"]) if w["labels"] else ""),
                    f"- **What it produces:** {f['produces']}"]
            if f["cloud_sees"]:
                out.append(f"- **What the Cloud sees:** {f['cloud_sees']}")
            out.append(f"- **Tests:** {tests_line(f)}")
            if f["limits"]:
                out.append("- **Limits:** " + " ".join(f["limits"]))
            out += [f"- **Status:** {STATUS[f['status']]}", ""]
    cs = data["cloud_sees_summary"]
    out += ["## What the Cloud sees, in one place", "",
            "It sees: " + "; ".join(cs["sees"]) + ".", "",
            "It never sees: " + "; ".join(cs["never_sees"]) + ".", "",
            "## Not included", ""]
    out += [f"- {n['claim']} Evidence: {n['evidence']}" for n in data["not_included"]]
    out += ["", "## App mismatches found while writing this", "",
            "Places where the app, its docs or the brief disagree. None is fixed yet.", ""]
    out += [f"- **{m['where']}:** {m['issue']}" for m in data["mismatches"]]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only check, write nothing")
    args = parser.parse_args()
    data = json.loads(FEATURES.read_text(encoding="utf-8"))
    problems = check(data)
    for p in problems:
        print("PROBLEM: " + p)
    if problems:
        return 1
    if not args.check:
        OUT.write_text(render(data), encoding="utf-8")
        print(f"Feature inventory: {len(data['features'])} features, written to {OUT.relative_to(ROOT)}")
    else:
        print(f"Feature inventory: {len(data['features'])} features, 0 problems")
    return 0


if __name__ == "__main__":
    sys.exit(main())
